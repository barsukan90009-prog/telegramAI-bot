    @classmethod
    def get_system_instruction(cls, mode: str) -> str:
        return cls.PROMPTS.get(mode, cls.PROMPTS["bydlo"])

    @classmethod
    def build_user_prompt(cls, history: list[str], user_name: str, prompt_text: str) -> str:
        history_context = "\n".join(history)
        msg_count = len(history)

        return (
            f"--- НАЧАЛО ТЕКСТА РЕПЛИК ЧАТА ({msg_count} СООБЩЕНИЙ) ---\n"
            f"{history_context}\n"
            f"--- КОНЕЦ ТЕКСТА РЕПЛИК ЧАТА ---\n\n"
            f"Участник {user_name} произносит: \"{prompt_text}\"\n\n"
            f"Ответь ему в соответствии со своей заданной ролью."
        )